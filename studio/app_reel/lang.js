var _lang = 'uz';

function detectLang() {
    var tgUser = window.Telegram && window.Telegram.WebApp && window.Telegram.WebApp.initDataUnsafe && window.Telegram.WebApp.initDataUnsafe.user;
    var code = (tgUser && tgUser.language_code) ? tgUser.language_code : (navigator.language || navigator.userLanguage || 'uz');
    code = code.toLowerCase().split('-')[0];
    _lang = LANGS[code] ? code : 'uz';
}

function t(key) {
    return (LANGS[_lang] && LANGS[_lang][key] !== undefined) ? LANGS[_lang][key] : (LANGS['uz'][key] || key);
}

function applyLang() {
    var els = document.querySelectorAll('[data-i18n]');
    for (var i = 0; i < els.length; i++) {
        var key = els[i].getAttribute('data-i18n');
        els[i].textContent = t(key);
    }
    var phs = document.querySelectorAll('[data-i18n-ph]');
    for (var j = 0; j < phs.length; j++) {
        var phKey = phs[j].getAttribute('data-i18n-ph');
        phs[j].placeholder = t(phKey);
    }
}